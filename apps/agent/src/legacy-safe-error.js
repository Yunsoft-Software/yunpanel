const fallback = Object.freeze({
  code: 'legacy_operation_failed',
  message: 'Legacy host operation failed. Inspect protected host diagnostics before retrying.',
});

export function safeLegacyAgentError(error) {
  let code;
  try { code = error?.code; } catch { /* Do not serialize hostile error objects. */ }
  return typeof code === 'string' && Object.hasOwn(messages, code)
    ? Object.freeze({ code, message: messages[code] })
    : fallback;
}

export function safeLegacyAgentDiagnosticCode(error, fallbackCode) {
  const safe = safeLegacyAgentError(error);
  if (safe !== fallback) return safe.code;
  return typeof fallbackCode === 'string' && /^[a-z0-9_.-]{1,80}$/.test(fallbackCode)
    ? fallbackCode
    : 'legacy_agent_failed';
}

export const legacySafeErrorInternals = Object.freeze({ messages, fallback });
